export function getAssetStatusGroup(asset) {
  const text = asset.status.toLowerCase();

  if (text.includes("completed")) {
    return "completed";
  }

  if (
    text.includes("progress") ||
    text.includes("tender")
  ) {
    return "ongoing";
  }

  return "published";
}
